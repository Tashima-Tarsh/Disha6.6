import fs from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, "../..");
const REGISTRY_PATH = path.join(ROOT_DIR, "data/osint/upstream-registry.json");
const MANIFEST_OUTPUT_PATH = path.join(ROOT_DIR, "web/lib/unified/generated/osint-tool-manifests.generated.ts");

function hashValue(value) {
  return crypto.createHash("sha256").update(JSON.stringify(value)).digest("hex");
}

export async function generateManifests() {
  console.info("Generating typed tool manifests from data/osint/upstream-registry.json...");
  const raw = await fs.readFile(REGISTRY_PATH, "utf8");
  const registry = JSON.parse(raw);

  console.info(`Processing all ${registry.length} tools for typed manifest generation...`);

  const manifestItems = registry.map((t) => {
    const safeToolId = t.toolId.replace(/[^a-zA-Z0-9_]/g, "_");
    const regDate = t.lastVerified || new Date().toISOString();
    const effectiveRuntime = t.workerRuntime || t.runtimeType || "system";
    let defaultCli = t.workerCommand;
    const repoSlug = (t.repo || t.toolId || "tool").toLowerCase();
    if (!defaultCli) {
      if (t.runtimeType === "python") defaultCli = `python -m ${repoSlug}`;
      else if (t.runtimeType === "node") defaultCli = `npx ${repoSlug}`;
      else if (t.runtimeType === "go") defaultCli = repoSlug;
      else defaultCli = t.toolId;
    }

    const manifestObj = {
      toolId: t.toolId,
      name: t.name,
      version: t.version || "1.0.0",
      repository: t.upstreamUrl,
      license: t.license || "Unknown",
      executionClass: t.executionClass || (["dataset-only", "gui-only", "library-only", "documentation"].includes(t.runtimeType) ? "catalog_only" : "passive_public"),
      targetTypes: (t.targetInputs && t.targetInputs.length > 0) ? t.targetInputs : ["general"],
      capabilities: (t.categories && t.categories.length > 0) ? t.categories : [t.category || "osint"],
      workerRuntime: effectiveRuntime,
      cliCommand: defaultCli,
      outputFormat: "json",
      timeoutMs: 60000,
      maxRetries: 1,
      rateLimitPerMinute: 6,
      legalUse: ["Authorized security analysis", "Defensive research", "Public OSINT lookup"],
      blockedUse: ["Surveillance", "Harassment", "Unauthorized intrusion"],
      registeredAt: regDate,
    };
    const manifestHash = hashValue(manifestObj);

    return {
      safeToolId,
      manifest: {
        ...manifestObj,
        manifestHash,
      },
    };
  });

  const tsContent = `// AUTOMATICALLY GENERATED BY scripts/osint/generate-manifests.mjs - DO NOT EDIT MANUALLY
import type { DishaToolManifest } from "../astra6-tool-manifest";

const SHELL_INJECTION_GUARD = /[;&|\`$(){}\\[\\]<>!\\n\\r\\\\"']/;

export type GeneratedOsintToolManifest = DishaToolManifest & {
  fullName: string;
  category: string;
  forkUrl: string | null;
  forkStatus: string;
  pinnedSha: string | null;
  upstreamSha: string | null;
  status: string;
};

export const generatedOsintManifests: GeneratedOsintToolManifest[] = [
${manifestItems.map(({ manifest }) => {
    const rawEntry = registry.find((r) => r.toolId === manifest.toolId) || {};
    return `  {
    toolId: ${JSON.stringify(manifest.toolId)},
    name: ${JSON.stringify(manifest.name)},
    version: ${JSON.stringify(manifest.version)},
    repository: ${JSON.stringify(manifest.repository)},
    license: ${JSON.stringify(manifest.license)},
    executionClass: ${JSON.stringify(manifest.executionClass)},
    targetTypes: ${JSON.stringify(manifest.targetTypes)},
    capabilities: ${JSON.stringify(manifest.capabilities)},
    workerRuntime: ${JSON.stringify(manifest.workerRuntime)},
    cliCommand: ${JSON.stringify(manifest.cliCommand)},
    outputFormat: ${JSON.stringify(manifest.outputFormat)},
    timeoutMs: ${manifest.timeoutMs},
    maxRetries: ${manifest.maxRetries},
    rateLimitPerMinute: ${manifest.rateLimitPerMinute},
    legalUse: ${JSON.stringify(manifest.legalUse)},
    blockedUse: ${JSON.stringify(manifest.blockedUse)},
    commandInjectionGuard: SHELL_INJECTION_GUARD,
    registeredAt: ${JSON.stringify(manifest.registeredAt)},
    manifestHash: ${JSON.stringify(manifest.manifestHash)},
    fullName: ${JSON.stringify(rawEntry.fullName || "")},
    category: ${JSON.stringify(rawEntry.category || "framework")},
    forkUrl: ${JSON.stringify(rawEntry.forkUrl || null)},
    forkStatus: ${JSON.stringify(rawEntry.forkStatus || "FORK_PENDING")},
    pinnedSha: ${JSON.stringify(rawEntry.pinnedSha || null)},
    upstreamSha: ${JSON.stringify(rawEntry.upstreamSha || null)},
    status: ${JSON.stringify(rawEntry.status || "CATALOGED")},
  },`;
  }).join("\n")}
];

export function getGeneratedManifest(toolId: string): GeneratedOsintToolManifest | undefined {
  return generatedOsintManifests.find((m) => m.toolId === toolId);
}

export function listGeneratedManifests(): GeneratedOsintToolManifest[] {
  return generatedOsintManifests.map((m) => ({ ...m }));
}
`;

  await fs.mkdir(path.dirname(MANIFEST_OUTPUT_PATH), { recursive: true });
  await fs.writeFile(MANIFEST_OUTPUT_PATH, tsContent, "utf8");
  console.info(`Generated ${manifestItems.length} tool manifests in ${MANIFEST_OUTPUT_PATH}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generateManifests().catch((err) => {
    console.error("Manifest generation error:", err);
    process.exitCode = 1;
  });
}
