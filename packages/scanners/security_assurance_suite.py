class GitleaksScanner:
    """Secret and credential exposure detection (Upstream 20: gitleaks/gitleaks)."""

    FALLBACK_SECRET_PATTERNS = [
        ("AWS Access Key", re.compile(r"(?:A3T[A-Z0-9]|AKIA|AGPA|AIDA|AROA|AIPA|ANPA|ANVA|ASIA)[A-Z0-9]{16}")),
        ("Generic Private Key", re.compile(r"-----BEGIN (?:RSA |EC |DSA |OPENSSH )?PRIVATE KEY-----")),
        ("Generic High-Entropy API Key", re.compile(r"""(?:api_key|apikey|secret|token)\s*[:=]\s*["']([A-Za-z0-9_\-]{24,})["']""", re.I)),
    ]

    def __init__(self, binary_path: Optional[str] = None):
        self.binary_path = binary_path or shutil.which("gitleaks")

    def is_available(self) -> bool:
        return self.binary_path is not None and os.path.exists(self.binary_path)

    def get_version(self) -> Optional[str]:
        if not self.is_available():
            return None
        try:
            res = subprocess.run([self.binary_path, "version"], capture_output=True, text=True, timeout=5)
            return res.stdout.strip()
        except Exception:
            return None

    def scan(self, target_path: str, allow_heuristic_fallback: bool = False) -> Dict[str, Any]:
        """
        Executes genuine upstream Gitleaks CLI against target path.
        If binary is not installed, returns NOT_INSTALLED unless heuristic fallback is explicitly allowed.
        """
        if not os.path.exists(target_path):
            return {
                "status": "TARGET_NOT_FOUND",
                "engine": "gitleaks",
                "target": target_path,
                "findings": [],
            }

        if self.is_available():
            try:
                with tempfile.NamedTemporaryFile(suffix=".json", delete=False) as tmp_report:
                    report_file = tmp_report.name

                cmd = [
                    self.binary_path,
                    "detect",
                    "--no-git",
                    "--source", os.path.abspath(target_path),
                    "--report-format", "json",
                    "--report-path", report_file,
                    "-v",
                ]
                proc = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
                findings = []
                if os.path.exists(report_file):
                    try:
                        with open(report_file, "r", encoding="utf-8") as f:
                            raw = f.read().strip()
                            if raw:
                                findings = json.loads(raw)
                    finally:
                        try:
                            os.remove(report_file)
                        except OSError:
                            pass

                return {
                    "status": "COMPLETED",
                    "engine": "gitleaks (upstream CLI)",
                    "binary_path": self.binary_path,
                    "target": target_path,
                    "exit_code": proc.returncode,
                    "findings": findings,
                }
            except Exception as e:
                return {
                    "status": "EXECUTION_ERROR",
                    "engine": "gitleaks",
                    "error": str(e),
                    "target": target_path,
                    "findings": [],
                }

        if not allow_heuristic_fallback:
            return {
                "status": "NOT_INSTALLED",
                "engine": "gitleaks",
                "binary_path": None,
                "error": "Upstream gitleaks CLI is not installed on system PATH.",
                "install_guide": "Install gitleaks from https://github.com/gitleaks/gitleaks/releases or 'brew install gitleaks' / 'choco install gitleaks'.",
                "findings": [],
            }

        # Offline heuristic fallback path
        findings = self.scan_file(target_path) if os.path.isfile(target_path) else []
        return {
            "status": "HEURISTIC_FALLBACK",
            "engine": "local-regex-fallback",
            "warning": "gitleaks binary not installed; findings generated by offline regex heuristic rules.",
            "target": target_path,
            "findings": findings,
        }

    def scan_text(self, text: str, source_label: str = "buffer") -> List[Dict[str, Any]]:
        findings = []
        for name, pattern in self.FALLBACK_SECRET_PATTERNS:
            for match in pattern.finditer(text):
                findings.append({
                    "rule": name,
                    "source": source_label,
                    "matched": match.group(0)[:6] + "..." + match.group(0)[-4:],
                    "start": match.start(),
                    "severity": "CRITICAL",
                    "execution_mode": "HEURISTIC_FALLBACK",
                })
        return findings

    def scan_file(self, filepath: str) -> List[Dict[str, Any]]:
        if not os.path.exists(filepath):
            return []
        with open(filepath, "r", encoding="utf-8", errors="ignore") as f:
            content = f.read()
        return self.scan_text(content, source_label=filepath)


class SemgrepScanner:
    """Code security analysis & AST rule matching (Upstream 18: semgrep/semgrep)."""

    FALLBACK_CODE_RULES = [
        {
            "id": "python-unsafe-eval",
            "pattern": re.compile(r"\beval\s*\("),
            "severity": "CRITICAL",
            "message": "Use of eval() detected, which allows arbitrary code execution",
        },
        {
            "id": "python-shell-true",
            "pattern": re.compile(r"subprocess\.(?:run|Popen|call)\s*\([^)]*shell\s*=\s*True"),
            "severity": "HIGH",
            "message": "subprocess with shell=True detected without strict sanitization",
        },
        {
            "id": "js-inner-html",
            "pattern": re.compile(r"dangerouslySetInnerHTML"),
            "severity": "MEDIUM",
            "message": "dangerouslySetInnerHTML detected; ensure input is sanitized",
        },
    ]

    def __init__(self, binary_path: Optional[str] = None):
        self.binary_path = binary_path or shutil.which("semgrep")

    def is_available(self) -> bool:
        return self.binary_path is not None and os.path.exists(self.binary_path)

    def get_version(self) -> Optional[str]:
        if not self.is_available():
            return None
        try:
            res = subprocess.run([self.binary_path, "--version"], capture_output=True, text=True, timeout=5)
            return res.stdout.strip()
        except Exception:
            return None

    def scan(self, target_path: str, config: str = "auto", allow_heuristic_fallback: bool = False) -> Dict[str, Any]:
        """
        Executes genuine upstream Semgrep CLI against target path.
        If binary is not installed, returns NOT_INSTALLED unless heuristic fallback is explicitly allowed.
        """
        if not os.path.exists(target_path):
            return {
                "status": "TARGET_NOT_FOUND",
                "engine": "semgrep",
                "target": target_path,
                "findings": [],
            }

        if self.is_available():
            try:
                cmd = [
                    self.binary_path,
                    "scan",
                    "--config", config,
                    "--json",
                    os.path.abspath(target_path),
                ]
                proc = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
                findings = []
                try:
                    data = json.loads(proc.stdout)
                    findings = data.get("results", [])
                except Exception:
                    pass

                return {
                    "status": "COMPLETED",
                    "engine": "semgrep (upstream CLI)",
                    "binary_path": self.binary_path,
                    "target": target_path,
                    "exit_code": proc.returncode,
                    "findings": findings,
                }
            except Exception as e:
                return {
                    "status": "EXECUTION_ERROR",
                    "engine": "semgrep",
                    "error": str(e),
                    "target": target_path,
                    "findings": [],
                }

        if not allow_heuristic_fallback:
            return {
                "status": "NOT_INSTALLED",
                "engine": "semgrep",
                "binary_path": None,
                "error": "Upstream semgrep CLI is not installed on system PATH.",
                "install_guide": "Install semgrep via 'pip install semgrep' or https://semgrep.dev/docs/getting-started/.",
                "findings": [],
            }

        # Offline heuristic fallback path
        findings = []
        if os.path.isfile(target_path):
            with open(target_path, "r", encoding="utf-8", errors="ignore") as f:
                findings = self.scan_code(f.read(), filename=target_path)
        return {
            "status": "HEURISTIC_FALLBACK",
            "engine": "local-ast-fallback",
            "warning": "semgrep binary not installed; findings generated by offline regex heuristic rules.",
            "target": target_path,
            "findings": findings,
        }

    def scan_code(self, code: str, filename: str = "snippet") -> List[Dict[str, Any]]:
        findings = []
        for rule in self.FALLBACK_CODE_RULES:
            for match in rule["pattern"].finditer(code):
                findings.append({
                    "rule_id": rule["id"],
                    "severity": rule["severity"],
                    "message": rule["message"],
                    "file": filename,
                    "offset": match.start(),
                    "execution_mode": "HEURISTIC_FALLBACK",
                })
        return findings


class TrivyScanner:
    """Dependency and configuration security assessment (Upstream 19: aquasecurity/trivy)."""

    FALLBACK_ADVISORIES = {
        "lodash": {"<4.17.21": "CVE-2021-23337 Prototype Pollution"},
        "urllib3": {"<2.0.7": "CVE-2023-45803 Request body strip on redirect"},
    }

    def __init__(self, binary_path: Optional[str] = None):
        self.binary_path = binary_path or shutil.which("trivy")

    def is_available(self) -> bool:
        return self.binary_path is not None and os.path.exists(self.binary_path)

    def get_version(self) -> Optional[str]:
        if not self.is_available():
            return None
        try:
            res = subprocess.run([self.binary_path, "--version"], capture_output=True, text=True, timeout=5)
            return res.stdout.strip()
        except Exception:
            return None

    def scan(self, target_path: str, allow_heuristic_fallback: bool = False) -> Dict[str, Any]:
        """
        Executes genuine upstream Trivy CLI against target path.
        If binary is not installed, returns NOT_INSTALLED unless heuristic fallback is explicitly allowed.
        """
        if not os.path.exists(target_path):
            return {
                "status": "TARGET_NOT_FOUND",
                "engine": "trivy",
                "target": target_path,
                "findings": [],
            }

        if self.is_available():
            try:
                cmd = [
                    self.binary_path,
                    "fs",
                    "--format", "json",
                    os.path.abspath(target_path),
                ]
                proc = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
                findings = []
                try:
                    data = json.loads(proc.stdout)
                    results = data.get("Results", [])
                    for r in results:
                        for vuln in r.get("Vulnerabilities", []):
                            findings.append({
                                "vulnerability_id": vuln.get("VulnerabilityID"),
                                "package": vuln.get("PkgName"),
                                "installed_version": vuln.get("InstalledVersion"),
                                "fixed_version": vuln.get("FixedVersion"),
                                "severity": vuln.get("Severity"),
                                "title": vuln.get("Title"),
                            })
                except Exception:
                    pass

                return {
                    "status": "COMPLETED",
                    "engine": "trivy (upstream CLI)",
                    "binary_path": self.binary_path,
                    "target": target_path,
                    "exit_code": proc.returncode,
                    "findings": findings,
                }
            except Exception as e:
                return {
                    "status": "EXECUTION_ERROR",
                    "engine": "trivy",
                    "error": str(e),
                    "target": target_path,
                    "findings": [],
                }

        if not allow_heuristic_fallback:
            return {
                "status": "NOT_INSTALLED",
                "engine": "trivy",
                "binary_path": None,
                "error": "Upstream trivy CLI is not installed on system PATH.",
                "install_guide": "Install trivy from https://github.com/aquasecurity/trivy or 'brew install trivy' / 'choco install trivy'.",
                "findings": [],
            }

        # Offline heuristic fallback path
        findings = self.scan_manifest(target_path)
        return {
            "status": "HEURISTIC_FALLBACK",
            "engine": "local-manifest-advisories",
            "warning": "trivy binary not installed; findings generated by offline manifest advisory table.",
            "target": target_path,
            "findings": findings,
        }

    def scan_manifest(self, manifest_path: str) -> List[Dict[str, Any]]:
        findings = []
        if not os.path.exists(manifest_path):
            return findings

        if manifest_path.endswith("package.json"):
            try:
                with open(manifest_path, "r", encoding="utf-8") as f:
                    data = json.load(f)
                deps = {**data.get("dependencies", {}), **data.get("devDependencies", {})}
                for pkg, ver in deps.items():
                    if pkg in self.FALLBACK_ADVISORIES:
                        findings.append({
                            "package": pkg,
                            "installed_version": ver,
                            "advisory": self.FALLBACK_ADVISORIES[pkg],
                            "manifest": manifest_path,
                            "execution_mode": "HEURISTIC_FALLBACK",
                        })
            except Exception:
                pass
        return findings


class NucleiScanner:
    """Authorized template-based vulnerability assessment (Upstream 17: projectdiscovery/nuclei)."""

    AUTHORIZED_HOSTS = {"127.0.0.1", "localhost", "0.0.0.0"}

    def __init__(self, binary_path: Optional[str] = None):
        self.binary_path = binary_path or shutil.which("nuclei")

    def is_available(self) -> bool:
        return self.binary_path is not None and os.path.exists(self.binary_path)

    def get_version(self) -> Optional[str]:
        if not self.is_available():
            return None
        try:
            res = subprocess.run([self.binary_path, "-version"], capture_output=True, text=True, timeout=5)
            return res.stdout.strip()
        except Exception:
            return None

    def scan_target(self, target_url: str, check_headers: bool = True, allow_heuristic_fallback: bool = False) -> Dict[str, Any]:
        """
        Executes authorized scan on localhost target only.
        Rejects non-localhost targets immediately.
        If binary is not installed, returns NOT_INSTALLED unless heuristic fallback is explicitly allowed.
        """
        parsed = urllib.parse.urlparse(target_url)
        hostname = (parsed.hostname or "").lower()

        if hostname not in self.AUTHORIZED_HOSTS:
            return {
                "status": "SCOPE_DENIED",
                "target": target_url,
                "error": f"Target '{hostname}' is not authorized. Scans permitted on localhost only.",
                "findings": [],
            }

        if self.is_available():
            try:
                cmd = [
                    self.binary_path,
                    "-u", target_url,
                    "-jsonl",
                    "-silent",
                ]
                proc = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
                findings = []
                for line in proc.stdout.splitlines():
                    line = line.strip()
                    if line:
                        try:
                            findings.append(json.loads(line))
                        except Exception:
                            pass

                return {
                    "status": "COMPLETED",
                    "engine": "nuclei (upstream CLI)",
                    "binary_path": self.binary_path,
                    "target": target_url,
                    "exit_code": proc.returncode,
                    "findings": findings,
                }
            except Exception as e:
                return {
                    "status": "EXECUTION_ERROR",
                    "engine": "nuclei",
                    "error": str(e),
                    "target": target_url,
                    "findings": [],
                }

        if not allow_heuristic_fallback:
            return {
                "status": "NOT_INSTALLED",
                "engine": "nuclei",
                "binary_path": None,
                "target": target_url,
                "error": "Upstream nuclei CLI is not installed on system PATH.",
                "install_guide": "Install nuclei from https://github.com/projectdiscovery/nuclei or 'brew install nuclei' / 'go install github.com/projectdiscovery/nuclei/v3/cmd/nuclei@latest'.",
                "findings": [],
            }

        # Offline heuristic header probe fallback path
        findings = []
        started = time.time()
        try:
            req = urllib.request.Request(target_url, headers={"User-Agent": "DISHA-Nuclei-Authorized-Probe/6.6"})
            with urllib.request.urlopen(req, timeout=5) as response:
                headers = dict(response.headers)
                if "x-frame-options" not in {k.lower() for k in headers}:
                    findings.append({
                        "template_id": "missing-x-frame-options",
                        "severity": "LOW",
                        "target": target_url,
                        "description": "Target response lacks X-Frame-Options header (clickjacking protection)",
                        "execution_mode": "HEURISTIC_FALLBACK",
                    })
                if "content-security-policy" not in {k.lower() for k in headers}:
                    findings.append({
                        "template_id": "missing-csp",
                        "severity": "LOW",
                        "target": target_url,
                        "description": "Target response lacks Content-Security-Policy header",
                        "execution_mode": "HEURISTIC_FALLBACK",
                    })

                return {
                    "status": "HEURISTIC_FALLBACK",
                    "engine": "local-http-probe-fallback",
                    "warning": "nuclei binary not installed; findings generated by offline header probe.",
                    "target": target_url,
                    "http_status": response.status,
                    "duration_s": round(time.time() - started, 3),
                    "findings": findings,
                }
        except Exception as e:
            return {
                "status": "TARGET_UNREACHABLE",
                "engine": "local-http-probe-fallback",
                "target": target_url,
                "error": str(e),
                "findings": [],
            }


